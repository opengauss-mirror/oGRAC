#!/bin/bash
# Writes build/syssentry.auto.bazelrc from build/detect_syssentry.sh (same rules as Makefile/CMake).
set -e

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
OUT="${SCRIPT_DIR}/syssentry.auto.bazelrc"

eval "$("${SCRIPT_DIR}/detect_syssentry.sh")"

{
    echo "# Generated by build/gen_syssentry_bazelrc.sh — do not edit."
    echo "# Regenerate after OS change or when detect_syssentry.sh changes."
    if [[ "${ENABLE_XALARMD}" == "ON" ]]; then
        if [[ "${ENABLE_XALARM_REPORT_EVENT_LEN}" == "ON" ]]; then
            echo "build --define=ENABLE_XALARMD=sp4"
        else
            echo "build --define=ENABLE_XALARMD=legacy"
        fi
    else
        echo "# SysSentry off on this host (see build/detect_syssentry.sh)."
    fi
} > "${OUT}"

echo "Wrote ${OUT} (xalarmd=${ENABLE_XALARMD} report_len=${ENABLE_XALARM_REPORT_EVENT_LEN})"
